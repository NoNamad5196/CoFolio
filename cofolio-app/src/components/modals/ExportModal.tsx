const DISABLED_FORMATS = ['pdf', 'notion', 'vercel'] as const

function capitalize(s: string) {
  return s.charAt(0).toUpperCase() + s.slice(1)
}

function generateMarkdown(state: BuilderState, _result: PortfolioResult | null): string {
  const { profile, projects, stack, about } = state
  const stackEntries = (Object.entries(stack) as Array<[string, string[]]>).filter(([, v]) => v.length > 0)
  const lines: string[] = []

  if (profile.name) {
    lines.push(`# ${profile.name}${profile.role ? ` — ${profile.role}` : ''}`)
  }
  if (profile.location) lines.push(`\n📍 ${profile.location}`)
  if (profile.bio) lines.push(`\n> ${profile.bio}`)

  if (about.intro || about.career || about.goals) {
    lines.push('\n---\n\n## About\n')
    if (about.intro) lines.push(about.intro)
    if (about.career) lines.push(`\n${about.career}`)
    if (about.goals) lines.push(`\n${about.goals}`)
  }

  if (stackEntries.length > 0) {
    lines.push('\n---\n\n## Tech Stack\n')
    stackEntries.forEach(([k, v]) => {
      lines.push(`**${capitalize(k)}**: ${v.join(', ')}  `)
    })
  }

  if (projects.length > 0) {
    lines.push('\n---\n\n## Projects\n')
    projects.forEach((p) => {
      lines.push(`### ${p.title || '프로젝트'}${p.role ? ` — ${p.role}` : ''}`)
      if (p.desc) lines.push(p.desc)
      const linkParts: string[] = []
      if (p.github) linkParts.push(`🔗 [${p.github}](https://${p.github.replace(/^https?:\/\//, '')})`)
      if (p.deploy) linkParts.push(`🌐 [${p.deploy}](https://${p.deploy.replace(/^https?:\/\//, '')})`)
      if (linkParts.length) lines.push(linkParts.join(' · '))
      lines.push('')
    })
  }

  lines.push('---\n\n*Generated by [Cofolio](https://cofolio.app)*')
  return lines.join('\n')
}

function downloadHtml(state: BuilderState, portfolioName: string, theme: string): void {
  const { profile, projects, stack, about } = state
  const stackEntries = (Object.entries(stack) as Array<[string, string[]]>).filter(([, v]) => v.length > 0)
  const isDark = theme !== 'light'
  const bg = isDark ? '#0b0f1d' : '#ffffff'
  const fg = isDark ? '#e2e8f0' : '#1e293b'
  const sub = isDark ? '#94a3b8' : '#64748b'
  const border = isDark ? 'rgba(255,255,255,0.10)' : 'rgba(0,0,0,0.10)'
  const card = isDark ? 'rgba(255,255,255,0.03)' : 'rgba(0,0,0,0.03)'

  const stackHtml = stackEntries.map(([k, v]) =>
    `<div class="sg"><span class="sl">${capitalize(k)}</span>${v.map((t) => `<span class="tag">${t}</span>`).join('')}</div>`
  ).join('')

  const projectsHtml = projects.map((p) => {
    const links = [
      p.github ? `<a href="https://${p.github.replace(/^https?:\/\//, '')}" target="_blank" rel="noreferrer">GitHub →</a>` : '',
      p.deploy ? `<a href="https://${p.deploy.replace(/^https?:\/\//, '')}" target="_blank" rel="noreferrer">배포 →</a>` : '',
    ].filter(Boolean).join('')
    return `<div class="pc">
      <div class="pt">${p.title || '프로젝트'}${p.role ? `<span class="pr">${p.role}</span>` : ''}</div>
      ${p.desc ? `<div class="pd">${p.desc}</div>` : ''}
      ${links ? `<div class="pl">${links}</div>` : ''}
    </div>`
  }).join('')

  const html = `<!DOCTYPE html>
<html lang="ko">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1.0">
<title>${profile.name || 'Portfolio'} — Cofolio</title>
<style>
*{box-sizing:border-box;margin:0;padding:0}
body{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',sans-serif;background:${bg};color:${fg};line-height:1.6;padding:40px 20px}
.w{max-width:760px;margin:0 auto}
.hd{border-bottom:1px solid ${border};padding-bottom:24px;margin-bottom:32px}
h1{font-size:28px;font-weight:700;margin-bottom:4px}
.rl{color:${sub};font-size:14px;margin-bottom:8px}
.bi{font-size:15px}
h2{font-size:13px;font-weight:600;text-transform:uppercase;letter-spacing:.12em;color:${sub};margin:32px 0 12px}
.at{font-size:14px;line-height:1.8;margin-bottom:8px}
.sg{display:flex;flex-wrap:wrap;align-items:center;gap:8px;margin-bottom:8px}
.sl{font-size:12px;font-weight:600;color:${sub};min-width:80px}
.tag{display:inline-block;border:1px solid ${border};background:${card};padding:2px 10px;border-radius:6px;font-size:12px;font-family:monospace}
.pc{border:1px solid ${border};background:${card};border-radius:12px;padding:20px;margin-bottom:12px}
.pt{font-size:16px;font-weight:600;margin-bottom:6px}
.pr{display:inline-block;font-size:11px;font-weight:500;border:1px solid ${border};padding:1px 8px;border-radius:999px;margin-left:8px;vertical-align:middle}
.pd{font-size:13px;color:${sub};margin-bottom:10px;line-height:1.6}
.pl{display:flex;gap:12px}
.pl a{font-size:13px;color:#7c3aed;text-decoration:none}
.pl a:hover{text-decoration:underline}
.ft{margin-top:48px;padding-top:16px;border-top:1px solid ${border};font-size:12px;color:${sub};text-align:center}
.ft a{color:#7c3aed;text-decoration:none}
</style>
</head>
<body>
<div class="w">
  <div class="hd">
    <h1>${profile.name || 'Portfolio'}</h1>
    <div class="rl">${[profile.role, profile.location].filter(Boolean).join(' · ')}</div>
    ${profile.bio ? `<div class="bi">${profile.bio}</div>` : ''}
  </div>
  ${about.intro || about.career || about.goals ? `<h2>About</h2>
    ${about.intro ? `<div class="at">${about.intro}</div>` : ''}
    ${about.career ? `<div class="at">${about.career}</div>` : ''}
    ${about.goals ? `<div class="at">${about.goals}</div>` : ''}` : ''}
  ${stackEntries.length ? `<h2>Tech Stack</h2>${stackHtml}` : ''}
  ${projects.length ? `<h2>Projects</h2>${projectsHtml}` : ''}
  <div class="ft">Generated by <a href="https://cofolio.app">Cofolio</a></div>
</div>
</body>
</html>`

  const blob = new Blob([html], { type: 'text/html;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${(portfolioName || 'portfolio').replace(/\s+/g, '-')}-${theme}.html`
  document.body.appendChild(a)
  a.click()
  setTimeout(() => { document.body.removeChild(a); URL.revokeObjectURL(url) }, 100)
}

