// ── Component ─────────────────────────────────────────────────────────────────

interface Props {
  isOpen: boolean
  onClose: () => void
  portfolioName?: string
}

export function ExportModal({ isOpen, onClose, portfolioName = '포트폴리오' }: Props) {
  const { state, result } = useBuilder()
  const [format, setFormat] = useState('html')
  const [theme, setTheme] = useState('dark')
  const [busy, setBusy] = useState(false)
  const [done, setDone] = useState<{ title: string; sub: string } | null>(null)
  const [exportError, setExportError] = useState<string | null>(null)

  useEffect(() => {
    if (isOpen) { setBusy(false); setDone(null); setExportError(null) }
  }, [isOpen])

  useEffect(() => {
    if (!isOpen) return
    const prev = document.body.style.overflow
    document.body.style.overflow = 'hidden'
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose() }
    window.addEventListener('keydown', onKey)
    return () => { document.body.style.overflow = prev; window.removeEventListener('keydown', onKey) }
  }, [isOpen, onClose])

  if (!isOpen) return null

  const isDisabled = DISABLED_FORMATS.includes(format as typeof DISABLED_FORMATS[number])

  const handleExport = async () => {
    if (isDisabled || busy) return
    setBusy(true)
    setExportError(null)

    try {
      if (format === 'md') {
        const markdown = generateMarkdown(state, result)
        await navigator.clipboard.writeText(markdown)
        setDone({ title: 'Markdown이 복사되었습니다', sub: 'GitHub 프로필 README에 붙여넣어 보세요' })
      } else if (format === 'html') {
        downloadHtml(state, portfolioName, theme)
        setDone({ title: 'HTML 다운로드를 시작했어요', sub: `${portfolioName}-${theme}.html` })
      }
    } catch {
      setExportError('클립보드 복사에 실패했습니다. 브라우저 권한을 확인하거나 직접 복사해주세요.')
    } finally {
      setBusy(false)
    }
  }

  const selectedFormat = EXPORT_FORMATS.find((f) => f.id === format)
  const selectedTheme = EXPORT_THEMES.find((t) => t.id === theme)

  const actionLabel = () => {
    if (isDisabled) return '준비 중'
    if (format === 'md') return 'Markdown 복사'
    return '다운로드'
  }

  return (
    <div
      className="fixed inset-0 z-[80] flex items-center justify-center px-4"
      style={{ animation: 'fadeIn .2s ease' }}
      onClick={onClose}
    >
      <div className="absolute inset-0 bg-black/60 backdrop-blur-sm" />
      <div
        onClick={(e) => e.stopPropagation()}
        className="relative w-full max-w-[640px] rounded-2xl glass-strong overflow-hidden ring-grad"
        style={{ animation: 'popIn .3s cubic-bezier(.2,.7,.2,1)' }}
      >
        {/* Header */}
        <div className="px-6 pt-5 pb-4 border-b border-white/8 flex items-start justify-between gap-3">
          <div>
            <div className="text-[11px] uppercase tracking-[0.18em] text-violet-300/90">EXPORT</div>
            <div className="mt-1 text-[20px] font-semibold tracking-tight">포트폴리오 내보내기</div>
            <div className="mt-1 text-[12.5px] text-slate-400">형식과 테마를 선택하세요. 언제든 다시 만들 수 있어요.</div>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg border border-white/10 bg-white/[0.04] h-8 w-8 grid place-items-center text-slate-300 hover:bg-white/[0.08]"
            aria-label="닫기"
          >
            <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round"><path d="M18 6L6 18M6 6l12 12"/></svg>
          </button>
        </div>

        {/* Body */}
        {!done ? (
          <div className="px-6 py-5 space-y-5">
            {/* Format grid */}
            <div>
              <div className="text-[11px] uppercase tracking-[0.16em] text-slate-400 mb-2.5">형식</div>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
                {EXPORT_FORMATS.map((f) => {
                  const sel = format === f.id
                  const dis = DISABLED_FORMATS.includes(f.id as typeof DISABLED_FORMATS[number])
                  return (
                    <button
                      key={f.id}
                      onClick={() => !dis && setFormat(f.id)}
                      disabled={dis}
                      className={cn(
                        'text-left rounded-xl border p-3.5 transition flex items-start gap-3',
                        dis
                          ? 'border-white/8 bg-white/[0.015] opacity-50 cursor-not-allowed'
                          : sel
                          ? 'border-violet-400/60 bg-violet-500/[0.08] ring-1 ring-violet-400/30'
                          : 'border-white/10 bg-white/[0.03] hover:bg-white/[0.06]'
                      )}
                    >
                      <div className={cn(
                        'grid h-9 w-9 place-items-center rounded-lg shrink-0',
                        sel && !dis ? 'bg-gradient-to-br from-violet-500/30 to-cyan-500/20 text-violet-100' : 'bg-white/[0.04] text-slate-300'
                      )}>
                        {FORMAT_ICONS[f.id]}
                      </div>
                      <div className="min-w-0 flex-1">
                        <div className="flex items-center gap-2">
                          <div className="text-[13.5px] font-semibold text-slate-100">{f.title}</div>
                          {dis
                            ? <Tag tone="violet">준비 중</Tag>
                            : f.badge
                            ? <Tag tone="violet">{f.badge}</Tag>
                            : null}
                        </div>
                        <div className="mt-0.5 text-[11.5px] text-slate-400 leading-snug">{f.desc}</div>
                      </div>
                      <div className={cn('mt-0.5 h-4 w-4 shrink-0 rounded-full border', sel && !dis ? 'border-violet-400 bg-violet-400' : 'border-white/20')}>
                        {sel && !dis && (
                          <svg viewBox="0 0 16 16" className="h-full w-full text-white">
                            <path d="M3.5 8.5l3 3 6-7" stroke="currentColor" strokeWidth="2" fill="none" strokeLinecap="round" strokeLinejoin="round"/>
                          </svg>
                        )}
                      </div>
                    </button>
                  )
                })}
              </div>
            </div>

            {/* Theme picker */}
            <div>
              <div className="text-[11px] uppercase tracking-[0.16em] text-slate-400 mb-2.5">테마</div>
              <div className="grid grid-cols-3 gap-2.5">
                {EXPORT_THEMES.map((t) => {
                  const sel = theme === t.id
                  return (
                    <button
                      key={t.id}
                      onClick={() => setTheme(t.id)}
                      className={cn(
                        'rounded-xl border p-3 text-left transition',
                        sel ? 'border-violet-400/60 bg-violet-500/[0.08] ring-1 ring-violet-400/30' : 'border-white/10 bg-white/[0.03] hover:bg-white/[0.06]'
                      )}
                    >
                      <div className="h-12 w-full rounded-lg border border-white/10" style={{ background: t.swatch }} />
                      <div className="mt-2 text-[12.5px] font-semibold text-slate-100">{t.title}</div>
                      <div className="text-[10.5px] text-slate-400 leading-snug">{t.sub}</div>
                    </button>
                  )
                })}
              </div>
            </div>

            {/* Error */}
            {exportError && (
              <div className="rounded-xl border border-red-400/30 bg-red-500/10 px-3.5 py-2.5 text-[12.5px] text-red-300">
                {exportError}
              </div>
            )}

            {/* Info note */}
            <div className="rounded-xl border border-white/8 bg-white/[0.03] px-3.5 py-2.5 flex items-center gap-2.5">
              <div className="h-7 w-7 grid place-items-center rounded-md bg-violet-500/15 text-violet-200">
                <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8"><circle cx="12" cy="12" r="10"/><path d="M12 8v5M12 16h.01"/></svg>
              </div>
              <div className="text-[11.5px] text-slate-400 leading-snug">
                내보낸 결과물에는 Cofolio 워터마크가 포함되지 않습니다. Pro 플랜에서는 커스텀 도메인 연결도 가능해요.
              </div>
            </div>
          </div>
        ) : (
          <div className="px-6 py-8 text-center">
            <div className="mx-auto h-14 w-14 grid place-items-center rounded-full bg-gradient-to-br from-emerald-500/30 to-cyan-500/20 ring-1 ring-emerald-400/40">
              <svg width="26" height="26" viewBox="0 0 24 24" fill="none" stroke="#34d399" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round"><path d="M5 12.5l4.5 4.5L19 7"/></svg>
            </div>
            <div className="mt-3 text-[18px] font-semibold tracking-tight">{done.title}</div>
            <div className="mt-1 text-[12.5px] text-slate-400 break-all">{done.sub}</div>
          </div>
        )}

        {/* Footer */}
        <div className="border-t border-white/8 bg-white/[0.02] px-6 py-3.5 flex items-center justify-between gap-3">
          <div className="text-[11.5px] text-slate-500">
            {!done && <>선택: <span className="text-slate-300">{selectedFormat?.title}</span> · <span className="text-slate-300">{selectedTheme?.title}</span></>}
            {done && <>완료 — 다른 형식으로도 내보낼 수 있어요.</>}
          </div>
          <div className="flex items-center gap-2">
            {!done ? (
              <>
                <button onClick={onClose} className="rounded-lg border border-white/10 bg-white/[0.04] px-3.5 h-9 text-[12.5px] text-slate-200 hover:bg-white/[0.08]">취소</button>
                <PrimaryBtn size="sm" onClick={handleExport} disabled={busy || isDisabled}>
                  {busy ? (
                    <>
                      <svg width="14" height="14" viewBox="0 0 24 24" className="animate-spin">
                        <circle cx="12" cy="12" r="9" stroke="currentColor" strokeWidth="2.5" fill="none" strokeDasharray="42" strokeDashoffset="20"/>
                      </svg>
                      처리 중…
                    </>
                  ) : (
                    <>
                      {actionLabel()}
                      <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round"><path d="M5 12h14M13 6l6 6-6 6"/></svg>
                    </>
                  )}
                </PrimaryBtn>
              </>
            ) : (
              <>
                <button onClick={() => { setDone(null); setExportError(null) }} className="rounded-lg border border-white/10 bg-white/[0.04] px-3.5 h-9 text-[12.5px] text-slate-200 hover:bg-white/[0.08]">다시 내보내기</button>
                <PrimaryBtn size="sm" onClick={onClose}>완료</PrimaryBtn>
              </>
            )}
          </div>
        </div>
      </div>
    </div>
  )
}
